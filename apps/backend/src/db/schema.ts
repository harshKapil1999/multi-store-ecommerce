export const ProductTable = pgTable('product', {
  storeId: text('storeId').notNull().references(() => StoreTable._id),
  name: text('name').notNull(),
  slug: text('slug').notNull(),
  description: text('description').default(""),
  featuredImage: text('featuredImage').notNull(),
  mediaGallery: jsonb('mediaGallery').default([]),
  mrp: numeric('mrp', { precision: 12, scale: 2, mode: 'number' }).notNull(),
  sellingPrice: numeric('sellingPrice', { precision: 12, scale: 2, mode: 'number' }).notNull(),
  categoryId: text('categoryId').notNull().references((): AnyPgColumn => CategoryTable._id),
  attributes: jsonb('attributes').default([]),
  isFeatured: boolean('isFeatured').default(false),
  sku: text('sku'),
  isActive: boolean('isActive').default(true),
  stock: doublePrecision('stock').notNull().default(0),
  hasVariants: boolean('hasVariants').default(false),
  variantOptions: jsonb('variantOptions').default([]),
  _id: text('_id').primaryKey(),
  createdAt: timestamp('createdAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
  updatedAt: timestamp('updatedAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
}, (t) => [
  index('product_idx_0').on(t.storeId),
  index('product_idx_1').on(t.slug),
  index('product_idx_2').on(t.categoryId),
  index('product_idx_3').on(t.isFeatured),
  index('product_idx_4').on(t.isActive),
  uniqueIndex('product_idx_5').on(t.storeId, t.slug),
  check('product_stock_nonnegative', sql`${t.stock} >= 0`),
  index('product_catalog_idx').on(t.storeId, t.isActive, t.categoryId, t.createdAt),
  index('product_search_idx').using('gin', sql`to_tsvector('simple', coalesce(${t.name}, '') || ' ' || coalesce(${t.description}, ''))`),
  check('product_mrp_nonnegative', sql`${t.mrp} >= 0`),
  check('product_sellingPrice_nonnegative', sql`${t.sellingPrice} >= 0`),
]);

