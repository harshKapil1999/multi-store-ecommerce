// Shipping operations are persisted before external calls. Ambiguous results
// require reconciliation rather than repeating a potentially billable request.
export const ShipmentTable = pgTable('shipment', {
  orderId: text('order_id').primaryKey().references(() => OrderTable._id),
  providerOrderId: text('provider_order_id').unique(),
  providerShipmentId: text('provider_shipment_id').unique(),
  state: text('state').notNull().default('creating'),
  operation: text('operation'),
  parcel: jsonb('parcel').notNull(),
  awb: text('awb').unique(),
  courier: text('courier'),
  labelUrl: text('label_url'),
  pickupScheduled: boolean('pickup_scheduled').notNull().default(false),
  lastEventAt: timestamp('last_event_at', { precision: 3, withTimezone: true }),
  lastStatus: text('last_status'),
  createdAt: timestamp('created_at', { precision: 3, withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { precision: 3, withTimezone: true }).notNull().defaultNow(),
});
