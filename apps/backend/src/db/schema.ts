export const OrderTable = pgTable('order', {
  checkoutKey: text('checkoutKey'),
  checkoutFingerprint: text('checkoutFingerprint'),
  paymentCreationStartedAt: timestamp('paymentCreationStartedAt', { precision: 3, withTimezone: true, mode: 'date' }),
  inventoryStatus: text('inventoryStatus').default("uncommitted"),
  storeId: text('storeId').notNull().references(() => StoreTable._id),
  orderNumber: text('orderNumber').notNull(),
  customer: jsonb('customer'),
  items: jsonb('items').default([]),
  subtotal: numeric('subtotal', { precision: 12, scale: 2, mode: 'number' }).notNull(),
  tax: numeric('tax', { precision: 12, scale: 2, mode: 'number' }).default(0),
  shipping: numeric('shipping', { precision: 12, scale: 2, mode: 'number' }).default(0),
  discount: numeric('discount', { precision: 12, scale: 2, mode: 'number' }).default(0),
  total: numeric('total', { precision: 12, scale: 2, mode: 'number' }).notNull(),
  status: text('status').default("pending"),
  paymentStatus: text('paymentStatus').default("pending"),
  paymentMethod: text('paymentMethod'),
  transactionId: text('transactionId'),
  razorpayOrderId: text('razorpayOrderId'),
  shippingAddress: jsonb('shippingAddress'),
  billingAddress: jsonb('billingAddress'),
  fulfillment: jsonb('fulfillment'),
  statusHistory: jsonb('statusHistory').default([]),
  notes: text('notes'),
  _id: text('_id').primaryKey(),
  createdAt: timestamp('createdAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
  updatedAt: timestamp('updatedAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
}, (t) => [
  uniqueIndex('order_idx_0').on(t.checkoutKey),
  index('order_idx_1').on(t.storeId),
  uniqueIndex('order_idx_2').on(t.orderNumber),
  index('order_idx_3').on(t.status),
  index('order_idx_4').on(t.paymentStatus),
  index('order_idx_5').on(t.transactionId),
  index('order_idx_6').on(t.razorpayOrderId),
  index('order_customer_email_idx').on(sql`lower(${t.customer}->>'email')`),
  index('order_customer_user_idx').on(sql`(${t.customer}->>'userId')`),
  index('order_store_created_idx').on(t.storeId, t.createdAt),
  check('order_inventoryStatus_enum', sql`${t.inventoryStatus} in ('uncommitted', 'committed', 'released', 'review')`),
  check('order_status_enum', sql`${t.status} in ('pending', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded')`),
  check('order_paymentStatus_enum', sql`${t.paymentStatus} in ('pending', 'paid', 'failed', 'refunded')`),
]);

