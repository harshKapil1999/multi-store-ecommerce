import { pgTable, text, doublePrecision, numeric, boolean, timestamp, jsonb, index, uniqueIndex, check } from 'drizzle-orm/pg-core';
import type { AnyPgColumn } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';

// Scalar fields are SQL columns; nested value objects and ordered lists use JSONB.
// Keep the public 24-character IDs so existing clients retain their API contract.
export const BillboardTable = pgTable('billboard', {
  storeId: text('storeId').notNull().references(() => StoreTable._id),
  categoryId: text('categoryId'),
  title: text('title').notNull(),
  subtitle: text('subtitle'),
  imageUrl: text('imageUrl').notNull(),
  ctaText: text('ctaText'),
  ctaLink: text('ctaLink'),
  order: doublePrecision('order').default(0),
  isActive: boolean('isActive').default(true),
  _id: text('_id').primaryKey(),
  createdAt: timestamp('createdAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
  updatedAt: timestamp('updatedAt', { precision: 3, withTimezone: true, mode: 'date' }).notNull().defaultNow(),
}, (t) => [
  index('billboard_idx_0').on(t.storeId),
  index('billboard_idx_1').on(t.categoryId),
  index('billboard_idx_2').on(t.order),
  index('billboard_idx_3').on(t.isActive),
  index('billboard_idx_4').on(t.storeId, t.order),
]);

